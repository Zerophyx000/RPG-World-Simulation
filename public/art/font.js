export const CELL_W = 6;
export const CELL_H = 9;

// Accented letters: a base letter plus a mark drawn in the two rows above.
const ACCENTS = {
  'ä': ['a', 'uml'], 'ö': ['o', 'uml'], 'ü': ['u', 'uml'], 'Ä': ['A', 'uml'], 'Ö': ['O', 'uml'], 'Ü': ['U', 'uml'], 'ë': ['e', 'uml'], 'ï': ['i', 'uml'],
  'é': ['e', 'acute'], 'è': ['e', 'grave'], 'ê': ['e', 'circ'], 'à': ['a', 'grave'], 'â': ['a', 'circ'], 'ô': ['o', 'circ'], 'î': ['i', 'circ'], 'û': ['u', 'circ'],
  'á': ['a', 'acute'], 'í': ['i', 'acute'], 'ó': ['o', 'acute'], 'ú': ['u', 'acute'], 'É': ['E', 'acute'], 'ç': ['c', 'cedilla'], 'ñ': ['n', 'tilde'],
};
const MARKS = {
  uml: [[1, 0], [3, 0]], acute: [[3, 0], [2, 1]], grave: [[1, 0], [2, 1]], circ: [[2, 0], [1, 1], [3, 1]], tilde: [[1, 1], [2, 0], [3, 1]], cedilla: [[2, 8]],
};
const SPECIAL = {
  '…': (g) => { for (const x of [0, 2, 4]) g.push([x, 6]); },
  '’': (g) => { g.push([2, 2], [2, 3]); }, '‘': (g) => { g.push([2, 2], [2, 3]); }, '“': (g) => { g.push([1, 2], [1, 3], [3, 2], [3, 3]); }, '”': (g) => { g.push([1, 2], [1, 3], [3, 2], [3, 3]); },
  '—': (g) => { for (let x = 0; x < 5; x++) g.push([x, 5]); }, '–': (g) => { for (let x = 0; x < 5; x++) g.push([x, 5]); },
  '·': (g) => { g.push([2, 5]); }, '•': (g) => { g.push([1, 4], [2, 4], [3, 4], [1, 5], [2, 5], [3, 5], [2, 3], [2, 6]); }, '×': (g) => { for (let i = 1; i < 5; i++) g.push([i, i + 1], [5 - i, i + 1]); },
  '✝': (g) => { for (let y = 1; y < 8; y++) g.push([2, y]); for (let x = 0; x < 5; x++) g.push([x, 3]); },
  '?': null,
};

/** Pixels of one glyph as [x, y] pairs within the 6 x 9 cell (rows 2..8 are the letter body). */
function glyphPixels(ch) {
  const out = [];
  const code = ch.charCodeAt(0);
  const bytes = (c) => ASCII.slice((c.charCodeAt(0) - 32) * 5, (c.charCodeAt(0) - 32) * 5 + 5);
  const body = (c) => { bytes(c).forEach((col, x) => { for (let y = 0; y < 7; y++) if (col & (1 << y)) out.push([x, y + 2]); }); };
  if (code >= 32 && code <= 126) body(ch);
  else if (ACCENTS[ch]) {
    const [base, mark] = ACCENTS[ch];
    body(base === base.toLowerCase() || /[A-Z]/.test(base) ? base : base);
    const lift = /[A-Z]/.test(base) ? 0 : 0;
    for (const [x, y] of MARKS[mark]) out.push([x, y + lift]);
    if (mark === 'cedilla') return out;
  } else if (ch === 'ß') {
    body('B');
  } else if (SPECIAL[ch]) {
    const g = []; SPECIAL[ch](g); for (const [x, y] of g) out.push([x, y + 2]);
  } else body('?');
  return out;
}

const cache = new Map();
function glyph(ch) {
  let g = cache.get(ch);
  if (!g) { g = glyphPixels(ch); cache.set(ch, g); }
  return g;
}

/** Width in pixels of a string (6 per character). */
export function textWidth(str) {
  return String(str).length * CELL_W - 1;
}

/** Draw `str` into an Img at (x, y). opts: { color, shadow (colour for a 1-px drop shadow), outline (colour), scale } */
export function drawText(img, x, y, str, opts = {}) {
  const color = opts.color ?? [255, 255, 255, 255];
  const scale = opts.scale ?? 1;
  let cx = x;
  for (const ch of String(str)) {
    for (const [gx, gy] of glyph(ch)) {
      const px = cx + gx * scale; const py = y + gy * scale;
      if (opts.outline) for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) img.rect(px + dx * scale, py + dy * scale, scale, scale, opts.outline);
    }
    cx += CELL_W * scale;
  }
  cx = x;
  for (const ch of String(str)) {
    for (const [gx, gy] of glyph(ch)) {
      const px = cx + gx * scale; const py = y + gy * scale;
      if (opts.shadow) img.rect(px + scale, py + scale, scale, scale, opts.shadow);
    }
    cx += CELL_W * scale;
  }
  cx = x;
  for (const ch of String(str)) {
    for (const [gx, gy] of glyph(ch)) img.rect(cx + gx * scale, y + gy * scale, scale, scale, color);
    cx += CELL_W * scale;
  }
  return img;
}

/** A small Img with the text on it (cached by callers). */
export function textImg(str, opts = {}) {
  const pad = opts.outline || opts.shadow ? 1 : 0;
  const img = new Img(textWidth(str) * (opts.scale ?? 1) + 2 + pad * 2, CELL_H * (opts.scale ?? 1) + 2 + pad * 2);
  return drawText(img, 1 + pad, 1 + pad, str, opts);
}

/** Wrap text to lines of at most `max` characters (words kept whole), at most `lines` lines; the last is shortened with "…". */
export function wrapText(str, max = 28, lines = 4) {
  const words = String(str).replace(/\s+/g, ' ').trim().split(' ');
  const out = [];
  let cur = '';
  for (const w of words) {
    if ((cur + ' ' + w).trim().length > max && cur) { out.push(cur); cur = w; } else cur = (cur + ' ' + w).trim();
  }
  if (cur) out.push(cur);
  if (out.length > lines) {
    out.length = lines;
    out[lines - 1] = `${out[lines - 1].slice(0, max - 1).replace(/[ ,.;:]+$/, '')}…`;
  }
  return out.map((l) => (l.length > max ? `${l.slice(0, max - 1)}…` : l));
}
