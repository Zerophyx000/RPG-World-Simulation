// Step 9 check (server): trip hooks and paths, the wear map, decals, position events and replay, perception,
// the social read model and interest scores. In-process world, no LLM.
import fs from 'node:fs';
const [,, root = process.cwd(), dataDir = `${process.env.TEMP ?? '/tmp'}/aw-traces9`] = process.argv;
fs.rmSync(dataDir, { recursive: true, force: true });
process.env.DATA_DIR = dataDir; process.env.SCENARIO = 'village'; process.env.LLM_BASE_URL = 'http://localhost:9/v1'; process.env.SPOT_WALKING = 'false';
const imp = (p) => import(`file:///${root}/${p}`);
const { openDb, migrate } = await imp('server/db.js');
const { World } = await imp('server/world.js');
const { replay } = await imp('server/ui/replay.js');
const { perceptionOf } = await imp('server/ui/perception.js');
const { socialView } = await imp('server/ui/social.js');
const { interest } = await imp('server/ui/interest.js');
const { buildMessages } = await imp('server/agents/prompt.js');
let pass = 0; let fail = 0;
const ok = (c, m) => { if (c) pass++; else fail++; console.log(`${c ? 'PASS' : 'FAIL'}  ${m}`); };
let db = openDb(); await migrate(db);
let w = new World(db);
const quiet = (x) => { x.scheduler.run = () => {}; x.scheduler.poke = () => {}; x.clock.running = true; for (const c of x.citizens.values()) { c.needsPlan = false; c.thinkCooldownUntil = 1e9; } };
quiet(w);
const advance = (m, step = 0.25) => { for (let t = 0; t < m; t += step) { w.clock.gameMinutes += step; for (const h of [...w.clock.handlers]) h(step, w.clock.gameMinutes); for (const c of w.citizens.values()) if (c.alive) { c.needs.hunger = Math.min(c.needs.hunger, 10); c.needs.fatigue = Math.min(c.needs.fatigue, 20); } } };
const C = (id) => w.citizens.get(id);
const goTo = (id, dest) => { w.applyAction(C(id), { name: 'move_to', arguments: { destination: dest } }); advance(6); };

console.log('\n--- trips, paths and the wear map');
const t0 = w.now;
goTo('greta', 'square');
ok(C('greta').location === 'square', 'greta walked to the square');
const pos = db.prepare("SELECT data FROM events WHERE type = 'position' AND actor_id = 'greta' ORDER BY id").all().map((r) => JSON.parse(r.data));
ok(pos.some((p) => p.kind === 'trip-start') && pos.some((p) => p.kind === 'trip-end' && p.path?.length > 5), `position events with a server path (${pos.at(-1)?.path?.length} tiles)`);
for (let i = 0; i < 4; i++) { goTo('greta', 'tavern'); goTo('greta', 'square'); }
const wear = w.wear.view().maps[0];
const path = pos.at(-1).path;
const onPath = path.map(([x, y]) => wear.wear[y * wear.w + x]);
ok(onPath.every((v) => v > 0) && wear.wear[2 * wear.w + 2] === 0, `wear along the path (${Math.min(...onPath)}..${Math.max(...onPath)}), none far away`);
const before = Math.max(...onPath);
advance(1440 * 3, 5);
const after = Math.max(...path.map(([x, y]) => w.wear.view().maps[0].wear[y * wear.w + x]));
ok(after < before && after > before * 0.85, `it fades slowly: ${before} -> ${after} after 3 days`);

console.log('\n--- decals');
w.directorEvent({ roomId: 'bakery', texts: { here: 'BOOM.' }, roomEffect: { text: 'An explosion blew out the shutters; soot everywhere.', durationGameMinutes: 600 } });
let marks = w.decals.list();
ok(['soot', 'scorch', 'rubble'].every((k) => marks.some((d) => d.kind === k && d.roomId === 'bakery')), `a blast leaves soot, scorch and rubble (${marks.length} marks)`);
w.directorEvent({ roomId: 'square', texts: { here: 'It pours.' }, roomEffect: { text: 'Rain is pouring down; puddles everywhere.', durationGameMinutes: 120 } });
const puddles = w.decals.list().filter((d) => d.kind === 'puddle');
ok(puddles.length > 0, `rain leaves puddles (${puddles.length})`);
const r0 = puddles[0].r; advance(120, 5);
const p2 = w.decals.list().find((d) => d.id === puddles[0].id);
ok(p2 && p2.r < r0, `puddles shrink while they dry (${r0} -> ${p2?.r})`);
advance(180, 5);
ok(!w.decals.list().some((d) => d.kind === 'puddle'), 'and are gone after a few hours');
const wood = w.decals.add({ kind: 'blood', roomId: 'tavern', intensity: 1 });
const grass = w.decals.add({ kind: 'blood', roomId: 'well', intensity: 1 });
ok(wood.surface === 'wood' && ['grass', 'dirt', 'cobble', 'stone'].includes(grass.surface), `surfaces: ${wood.surface} / ${grass.surface}`);
advance(1440 * 2.5, 10);
const ids = new Set(w.decals.list().map((d) => d.id));
ok(ids.has(wood.id) && (grass.surface !== 'grass' && grass.surface !== 'dirt' ? true : !ids.has(grass.id)), 'blood lasts longer on wood than on grass');

console.log('\n--- perception, social, interest');
w.directorEvent({ effects: ['tomas', 'lena', 'greta'].map((id) => ({ type: 'move', target: id, to: 'tavern', notify: false })) });
const per = perceptionOf(w, 'greta');
const prompt = buildMessages(w, C('greta'))[1].content;
const who = (prompt.split('# WHO IS HERE\n')[1] ?? '').split('\n# ')[0];
ok(per.people.length >= 2 && per.people.every((p) => who.includes(p.label.split(' ')[0])), `perception lists the people with the labels the prompt uses (${per.people.map((p) => p.label).join(' | ').slice(0, 90)})`);
ok(per.objects.length > 0 && per.objects.every((id) => w.objects.get(id)?.roomId === 'tavern' || w.objects.get(id)?.holderId), `perception lists the objects she perceives (${per.objects.length})`);
C('greta').body.status = [...(C('greta').body.status ?? []), 'blind'];
ok(perceptionOf(w, 'greta').senses.blind === true, 'a blind citizen: senses.blind');
C('greta').body.status = C('greta').body.status.filter((s) => s !== 'blind');
w.emotions.bump(C('greta'), { type: 'anger', target: 'tomas', delta: 8, cause: 'test', source: 'test' });
const soc = socialView(w);
const pair = soc.pairs.find((p) => p.from === 'greta' && p.to === 'tomas');
ok(pair && pair.anger > 0 && soc.citizens.greta.emotions.some((e) => e.type === 'anger'), `social: greta -> tomas anger ${pair?.anger}`);
const per2 = perceptionOf(w, 'greta');
ok(per2.emphasis.dominant?.type === 'anger' && per2.people.find((p) => p.id === 'tomas')?.emphasis === 'target', 'angry: tomas is the target, the others fade');
w.directorEvent({ roomId: 'smithy', texts: { here: 'A crash from the smithy.' } });
let foc = interest(w).focuses;
ok(foc.some((f) => f.roomId === 'smithy' && f.importance >= 9 && f.caption), `interest: the director event (${foc.find((f) => f.roomId === 'smithy')?.caption})`);
C('lena').body.critical = { until: w.now + 12 }; C('lena').body.criticalLeft = 12;
foc = interest(w).focuses;
ok(foc[0]?.id === 'lena' && foc[0].importance === 10, `a critical bleeding window ranks first: "${foc[0]?.caption}"`);
C('lena').body.critical = null; C('lena').body.criticalLeft = null;

console.log('\n--- replay');
const rp = replay(w, { from: t0 - 1, to: t0 + 30 });
ok(rp.initial.citizens.greta.location === 'tavern', 'replay: greta starts in the tavern');
ok(rp.events.some((e) => e.type === 'position' && e.citizenId === 'greta' && e.kind === 'trip-start') && rp.events.every((e, i, a) => i === 0 || a[i - 1].t <= e.t), 'position events in time order');
const mid = pos.find((p) => p.kind === 'trip-start');
const startT = db.prepare("SELECT game_time FROM events WHERE type = 'position' AND actor_id = 'greta' ORDER BY id LIMIT 1").get().game_time;
const rm = replay(w, { from: startT + 0.1, to: startT + 5 });
ok(rm.initial.citizens.greta.activity.type === 'moving', 'a window starting mid-trip begins with her on the road');
w.applyAction(C('greta'), { name: 'say', arguments: { to: 'Tomas', text: 'We need to talk about the money.' } });
const tSay = w.now; advance(1);
const rl = replay(w, { from: tSay - 1, to: w.now });
ok(rl.events.some((e) => e.type === 'line' && /money/.test(e.text)), 'spoken lines are in the replay');
void mid;

console.log('\n--- marks survive a restart');
const n1 = w.decals.list().length; const wv = JSON.stringify(w.wear.view().maps[0].wear.slice(0, 2000));
w.stop(); db.close?.();
db = openDb(); await migrate(db); w = new World(db); quiet(w);
ok(w.decals.list().length === n1, `decals after a restart: ${w.decals.list().length}/${n1}`);
ok(JSON.stringify(w.wear.view().maps[0].wear.slice(0, 2000)) === wv, 'the wear map after a restart is the same');
w.stop();
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
